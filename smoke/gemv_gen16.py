import torch
import triton
import triton.language as tl

@triton.jit
def gemv_m16_rows(w_ptr, x_ptr, b_ptr, y_ptr, N, K: tl.constexpr, BN: tl.constexpr, BK: tl.constexpr):
    pid = tl.program_id(0)
    rows = pid * BN + tl.arange(0, BN)
    acc0 = tl.zeros((BN,), tl.float32)
    acc1 = tl.zeros((BN,), tl.float32)
    acc2 = tl.zeros((BN,), tl.float32)
    acc3 = tl.zeros((BN,), tl.float32)
    acc4 = tl.zeros((BN,), tl.float32)
    acc5 = tl.zeros((BN,), tl.float32)
    acc6 = tl.zeros((BN,), tl.float32)
    acc7 = tl.zeros((BN,), tl.float32)
    acc8 = tl.zeros((BN,), tl.float32)
    acc9 = tl.zeros((BN,), tl.float32)
    acc10 = tl.zeros((BN,), tl.float32)
    acc11 = tl.zeros((BN,), tl.float32)
    acc12 = tl.zeros((BN,), tl.float32)
    acc13 = tl.zeros((BN,), tl.float32)
    acc14 = tl.zeros((BN,), tl.float32)
    acc15 = tl.zeros((BN,), tl.float32)
    for k0 in range(0, K, BK):
        offs = k0 + tl.arange(0, BK)
        w = tl.load(w_ptr + rows[:, None] * K + offs[None, :], mask=rows[:, None] < N, other=0.0)
        x0 = tl.load(x_ptr + 0 * K + offs)
        acc0 += tl.sum((w * x0[None, :]).to(tl.float32), axis=1)
        x1 = tl.load(x_ptr + 1 * K + offs)
        acc1 += tl.sum((w * x1[None, :]).to(tl.float32), axis=1)
        x2 = tl.load(x_ptr + 2 * K + offs)
        acc2 += tl.sum((w * x2[None, :]).to(tl.float32), axis=1)
        x3 = tl.load(x_ptr + 3 * K + offs)
        acc3 += tl.sum((w * x3[None, :]).to(tl.float32), axis=1)
        x4 = tl.load(x_ptr + 4 * K + offs)
        acc4 += tl.sum((w * x4[None, :]).to(tl.float32), axis=1)
        x5 = tl.load(x_ptr + 5 * K + offs)
        acc5 += tl.sum((w * x5[None, :]).to(tl.float32), axis=1)
        x6 = tl.load(x_ptr + 6 * K + offs)
        acc6 += tl.sum((w * x6[None, :]).to(tl.float32), axis=1)
        x7 = tl.load(x_ptr + 7 * K + offs)
        acc7 += tl.sum((w * x7[None, :]).to(tl.float32), axis=1)
        x8 = tl.load(x_ptr + 8 * K + offs)
        acc8 += tl.sum((w * x8[None, :]).to(tl.float32), axis=1)
        x9 = tl.load(x_ptr + 9 * K + offs)
        acc9 += tl.sum((w * x9[None, :]).to(tl.float32), axis=1)
        x10 = tl.load(x_ptr + 10 * K + offs)
        acc10 += tl.sum((w * x10[None, :]).to(tl.float32), axis=1)
        x11 = tl.load(x_ptr + 11 * K + offs)
        acc11 += tl.sum((w * x11[None, :]).to(tl.float32), axis=1)
        x12 = tl.load(x_ptr + 12 * K + offs)
        acc12 += tl.sum((w * x12[None, :]).to(tl.float32), axis=1)
        x13 = tl.load(x_ptr + 13 * K + offs)
        acc13 += tl.sum((w * x13[None, :]).to(tl.float32), axis=1)
        x14 = tl.load(x_ptr + 14 * K + offs)
        acc14 += tl.sum((w * x14[None, :]).to(tl.float32), axis=1)
        x15 = tl.load(x_ptr + 15 * K + offs)
        acc15 += tl.sum((w * x15[None, :]).to(tl.float32), axis=1)
    b = tl.load(b_ptr + rows, mask=rows < N, other=0.0).to(tl.float32)
    tl.store(y_ptr + 0 * N + rows, (acc0 + b).to(y_ptr.dtype.element_ty), mask=rows < N)
    tl.store(y_ptr + 1 * N + rows, (acc1 + b).to(y_ptr.dtype.element_ty), mask=rows < N)
    tl.store(y_ptr + 2 * N + rows, (acc2 + b).to(y_ptr.dtype.element_ty), mask=rows < N)
    tl.store(y_ptr + 3 * N + rows, (acc3 + b).to(y_ptr.dtype.element_ty), mask=rows < N)
    tl.store(y_ptr + 4 * N + rows, (acc4 + b).to(y_ptr.dtype.element_ty), mask=rows < N)
    tl.store(y_ptr + 5 * N + rows, (acc5 + b).to(y_ptr.dtype.element_ty), mask=rows < N)
    tl.store(y_ptr + 6 * N + rows, (acc6 + b).to(y_ptr.dtype.element_ty), mask=rows < N)
    tl.store(y_ptr + 7 * N + rows, (acc7 + b).to(y_ptr.dtype.element_ty), mask=rows < N)
    tl.store(y_ptr + 8 * N + rows, (acc8 + b).to(y_ptr.dtype.element_ty), mask=rows < N)
    tl.store(y_ptr + 9 * N + rows, (acc9 + b).to(y_ptr.dtype.element_ty), mask=rows < N)
    tl.store(y_ptr + 10 * N + rows, (acc10 + b).to(y_ptr.dtype.element_ty), mask=rows < N)
    tl.store(y_ptr + 11 * N + rows, (acc11 + b).to(y_ptr.dtype.element_ty), mask=rows < N)
    tl.store(y_ptr + 12 * N + rows, (acc12 + b).to(y_ptr.dtype.element_ty), mask=rows < N)
    tl.store(y_ptr + 13 * N + rows, (acc13 + b).to(y_ptr.dtype.element_ty), mask=rows < N)
    tl.store(y_ptr + 14 * N + rows, (acc14 + b).to(y_ptr.dtype.element_ty), mask=rows < N)
    tl.store(y_ptr + 15 * N + rows, (acc15 + b).to(y_ptr.dtype.element_ty), mask=rows < N)