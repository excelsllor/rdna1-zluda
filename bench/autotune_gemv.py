"""Autotune the M=1 GEMV launch config on this GPU and write a config table.

The GEMV kernel is launched with (BK, num_warps); the best pair depends on the
(n, k) shape. This sweep measures the real kernel and writes
`zluda_ops/tuned_gemv_ext.py` (merged with the hand-tuned TUNED_M1 table in
zluda_ops/gemv.py).

Run under run-zluda.cmd:
    venv\\Scripts\\python.exe bench\\autotune_gemv.py
"""

import sys
import time
from pathlib import Path

import torch

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

SHAPES = [
    (896, 896),      # qkv/o projections (Qwen2.5-0.5B)
    (4864, 896),     # gate/up
    (896, 4864),     # down
    (151936, 896),   # lm_head
    (4096, 4096),    # large square projection
    (4864, 4864),    # large gate/up (7B class)
]
BKS = [128, 256, 512, 1024, 2048, 4096]
WARPS = [2, 4]
ITERS = 12


def bench(fn, n=ITERS):
    for _ in range(3):
        fn()
    torch.cuda.synchronize()
    t0 = time.perf_counter()
    for _ in range(n):
        fn()
    torch.cuda.synchronize()
    return (time.perf_counter() - t0) / n * 1e6


def main():
    if not torch.cuda.is_available():
        print("CUDA/ZLUDA device is not available")
        return 1
    torch.cuda.set_per_process_memory_fraction(0.6)
    from zluda_ops import gemv as G

    table = {}
    for n, k in SHAPES:
        x = torch.randn(1, k, device="cuda", dtype=torch.float16)
        w = torch.randn(n, k, device="cuda", dtype=torch.float16)
        y = torch.empty(1, n, device="cuda", dtype=torch.float16)
        best = None
        print(f"--- shape n={n} k={k} ---", flush=True)
        for bk in BKS:
            if k % bk:
                continue
            for warps in WARPS:
                def run(bk=bk, warps=warps):
                    G._gemv_kernel[(n,)](w, x, y, y, n, k, M=1, BK=bk,
                                         HAS_BIAS=False, PROD_F16=False,
                                         num_warps=warps, num_stages=1)
                try:
                    us = bench(run)
                except Exception as exc:  # noqa: BLE001
                    print(f"  bk={bk:5d} warps={warps}: {type(exc).__name__}", flush=True)
                    continue
                print(f"  bk={bk:5d} warps={warps}: {us:7.1f} us", flush=True)
                if best is None or us < best[0]:
                    best = (us, bk, warps)
        if best:
            table[(n, k)] = (best[1], best[2])
            print(f"  best: bk={best[1]} warps={best[2]} ({best[0]:.1f} us)", flush=True)
    out = Path(__file__).resolve().parents[1] / "zluda_ops" / "tuned_gemv_ext.py"
    lines = ['"""Auto-generated by bench/autotune_gemv.py (do not edit)."""', "",
             "TUNED_M1_EXT = {"]
    for (n, k), (bk, warps) in sorted(table.items()):
        lines.append(f"    ({n}, {k}): ({bk}, {warps}),")
    lines.append("}")
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nwrote {out} ({len(table)} entries)", flush=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
