"""Summarise the cross-backend re-measurement into a markdown report.

Reads the newest bench/results/vulkan_matrix-*.json (Ollama/Vulkan, FA=0) and all
bench/results/maxctx_matrix-*.json files produced by today's run, then writes
docs/ENGINE_COMPARISON_REMATRIX.md and prints the tables.

Usage:
  venv\\Scripts\\python.exe bench\\summarize_rematrix.py [--date YYYY-MM-DD]
"""

import argparse
import json
from datetime import date
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
RESULTS = REPO / "bench" / "results"
OUT = REPO / "docs" / "ENGINE_COMPARISON_REMATRIX.md"


def newest(pattern):
    files = sorted(RESULTS.glob(pattern), key=lambda p: p.stat().st_mtime,
                   reverse=True)
    return files


def load(path):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except Exception:  # noqa: BLE001
        return None


def _attn_label(attn):
    # sdpa_fast = default selector with the crashy fast backends disabled
    return {"sdpa_fast": "sdpa (fast off)"}.get(attn, attn)


VULKAN_DTYPE = {
    "qwen05-f32": "fp32",
    "qwen05-bf16": "bf16",
    "qwen05-f16": "fp16",
    "qwen05-q8": "q8_0",
    "qwen05-q4": "q4_k_m",
}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--date", default=str(date.today()))
    args = parser.parse_args()
    lines = [f"# Cross-backend re-measurement at max fitting context ({args.date})", "",
             "Generated by bench/summarize_rematrix.py from bench/results/*.json.",
             "Vulkan = Ollama/llama.cpp Vulkan backend, FA=0, KV f16.",
             "ZLUDA = PyTorch 2.7.1+cu118 under this fork; no FA, no compile.",
             "GPU clocks are not fixed (run-to-run spread 15-30%).", ""]

    # ---------- Vulkan ----------
    vrows = []
    for rep in newest("vulkan_matrix-*.json")[:1]:
        data = load(rep)
        if not data:
            continue
        for row in data.get("rows", []):
            if "error" in row:
                vrows.append({"model": row.get("model"), "ctx": row.get(
                    "requested_ctx"), "prefill": None, "decode": None,
                    "note": row["error"][:80]})
                continue
            vrows.append({"model": row.get("model"),
                          "ctx": row.get("requested_ctx"),
                          "vram_ctx": row.get("context_length"),
                          "prefill": row.get("prefill_tok_s"),
                          "decode": row.get("decode_tok_s")})
        lines += [f"Vulkan source: `{rep.name}`", ""]
        break
    if vrows:
        lines += ["## Vulkan (llama.cpp via Ollama, FA=0)", "",
                  "| model | requested ctx | actual ctx | prefill tok/s | decode tok/s |",
                  "|---|---|---|---|---|"]
        for r in vrows:
            lines.append(f"| {r['model']} | {r['ctx']} | {r.get('vram_ctx')} | "
                         f"{r.get('prefill')} | {r.get('decode')} |")
        lines.append("")

    # ---------- ZLUDA ----------
    zrows = []
    seen = set()
    for rep in newest("maxctx_matrix-*.json"):
        data = load(rep)
        if not data or not isinstance(data, dict):
            continue
        key = (data.get("dtype"), data.get("acc"), data.get("bf16_emul"),
               data.get("quant"), data.get("attn"))
        if key in seen:
            continue
        seen.add(key)
        best = data.get("max_ok_ctx")
        ctx_rows = data.get("contexts") or []
        last = ctx_rows[-1] if ctx_rows else {}
        zrows.append({"dtype": data.get("dtype"), "acc": data.get("acc"),
                      "emul": data.get("bf16_emul"),
                      "quant": data.get("quant"), "attn": data.get("attn"),
                      "max_ctx": best,
                      "prefill": last.get("prefill_tok_s"),
                      "decode": last.get("decode_tok_s"),
                      "peak_mb": last.get("peak_mb"),
                      "fail": (data.get("first_fail") or {}).get("ctx")})
    if zrows:
        zrows.sort(key=lambda r: (r["dtype"], r["attn"], r["quant"],
                                  r["acc"], r["emul"]))
        lines += ["## ZLUDA (PyTorch, max fitting context)", "",
                  "| dtype | acc | bf16-emul | quant | attn | max ctx | prefill tok/s | decode tok/s | peak MB | next ctx fails |",
                  "|---|---|---|---|---|---|---|---|---|---|"]
        for r in zrows:
            lines.append(
                f"| {r['dtype']} | {r['acc']} | {r['emul']} | {r['quant']} | "
                f"{{_attn_label(r['attn'])}} | {{r['max_ctx']}} | {{r['prefill']}} | "
                f"{r['decode']} | {r['peak_mb']} | {r['fail']} |")
        lines.append("")

    # ---------- mapping ----------
    lines += ["## Cross-backend mapping", "",
              "| dtype config | Vulkan equivalent | note |", "|---|---|---|",
              "| fp32 | F32 GGUF | |",
              "| fp16 | F16 GGUF | |",
              "| fp16 + accum | n/a | cuBLAS HPA only, llama.cpp computes in tensor type |",
              "| bf16 | BF16 GGUF | |",
              "| bf16-emul (fp32 compute) | n/a | llama.cpp equivalent absent |",
              "| q8 (int8 -> dequant fp32) | Q8_0 GGUF | both dequantize to compute precision |",
              "| q4 (int4 -> dequant fp32) | Q4_K_M GGUF | |",
              "| attention math/sdpa | FA=0 kernels | Vulkan FA=1 excluded from this run |", ""]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    print(f"\nreport: {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
