"""Apply the generated rematrix report to ENGINE_COMPARISON.md.

Replaces the "2026-11-27 re-measurement" section of ENGINE_COMPARISON.md (which
initially contains the plan/blocker note) with the tables generated by
bench/summarize_rematrix.py (docs/ENGINE_COMPARISON_REMATRIX.md).

Usage:
  venv\\Scripts\\python.exe bench\\apply_rematrix_to_engine_comparison.py [--dry-run]
"""

import argparse
import re
from datetime import datetime
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
ENGINE = REPO / "ENGINE_COMPARISON.md"
REMATRIX = REPO / "docs" / "ENGINE_COMPARISON_REMATRIX.md"
HEADING = "## 2026-11-27 re-measurement at max fitting context"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    if not REMATRIX.exists():
        print(f"missing {REMATRIX}; run bench/summarize_rematrix.py first")
        return 1
    if not ENGINE.exists():
        print(f"missing {ENGINE}")
        return 1
    report = REMATRIX.read_text(encoding="utf-8").strip().splitlines()
    # drop the report's own title, keep the tables
    while report and report[0].startswith("#"):
        report.pop(0)
    while report and not report[0].strip():
        report.pop(0)
    body = "\n".join(report)
    stamp = datetime.now().strftime("%Y-%m-%d %H:%M")
    new_section = (
        f"{HEADING} (completed {stamp})\n\n"
        "Measured with `tools/run_cross_backend_rematrix.ps1`; raw data in\n"
        "`bench/results/` (vulkan_matrix-*.json, maxctx_matrix-*.json), generated\n"
        "tables in `docs/ENGINE_COMPARISON_REMATRIX.md`.\n\n"
        f"{body}\n\n"
        "Reading: prefills/decode are single runs (GPU clocks are not fixed, so\n"
        "run-to-run spread is 15-30%). `max ctx` is the largest context that fits\n"
        "in 8 GB for that configuration; on the ZLUDA PyTorch side the attention\n"
        "implementation keeps the full SxS score matrix, so the fitting context is\n"
        "smaller than what llama.cpp/Vulkan can allocate with its tiled kernels.\n"
    )
    text = ENGINE.read_text(encoding="utf-8")
    idx = text.find(HEADING)
    if idx >= 0:
        # replace from the heading to the end of file (the section is last)
        text = text[:idx].rstrip() + "\n\n---\n\n" + new_section
        mode = "replaced"
    else:
        text = text.rstrip() + "\n\n---\n\n" + new_section
        mode = "appended"
    if args.dry_run:
        print(f"[dry-run] would have {mode} the section; preview:\n")
        print(new_section[:2000])
        return 0
    ENGINE.write_text(text, encoding="utf-8")
    print(f"{mode} rematrix section in {ENGINE}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
